import { nextTick, reactive } from 'vue'
import { afterEach, describe, expect, it, vi } from 'vitest'
import { useMockUi } from '../../../src/mock/useMockUi'

function ready() {
  const ui = reactive(useMockUi())
  ui.loadHistory('ready')
  return ui
}
function saving(ui: ReturnType<typeof ready>) {
  ui.fillExample()
  ui.requestDraft('save')
  ui.confirmDialog()
}
function recording(ui: ReturnType<typeof ready>) {
  ui.toggleListening()
  ui.finishStartup()
  ui.startInput()
}
afterEach(() => vi.unstubAllGlobals())

describe('Phase 2 Mock UI coordination', () => {
  it('automatically starts normal listening and allows stopping, but not during recording', async () => {
    const ui = ready()
    ui.toggleListening()
    expect(ui.starting).toBe(true)
    await nextTick()
    expect(ui.starting).toBe(false)
    expect(ui.microphone).toBe('LISTENING')
    ui.toggleListening()
    expect(ui.microphone).toBe('IDLE')
    ui.toggleListening()
    await nextTick()
    ui.startInput()
    ui.toggleListening()
    expect(ui.microphone).toBe('RECORDING')
  })
  it('does not let an old automatic start complete a newer request', async () => {
    const ui = ready()
    ui.toggleListening()
    ui.cancelStartup()
    ui.toggleListening()
    ui.finishStartup(1)
    expect(ui.starting).toBe(true)
    expect(ui.microphone).toBe('IDLE')
    await nextTick()
    expect(ui.microphone).toBe('LISTENING')
  })
  it('automatically reports startup failure without blocking manual input', async () => {
    const ui = ready()
    ui.speechFailure = true
    ui.toggleListening()
    await nextTick()
    expect(ui.microphone).toBe('IDLE')
    expect(ui.starting).toBe(false)
    expect(ui.message).toContain('启动失败')
    expect(ui.editable).toBe(true)
  })
  it('automatically saves only after confirmation, preserving zero and identifier text', async () => {
    const ui = ready()
    ui.fillExample()
    ui.updateField('workOrder', 'aB-007 X')
    ui.updateField('contactResistance', 0)
    ui.requestDraft('save')
    await nextTick()
    expect(ui.draftState).toBe('CONFIRMING_SAVE')
    expect(ui.records).toHaveLength(2)
    ui.confirmDialog()
    expect(ui.draftState).toBe('SAVING')
    expect(ui.records).toHaveLength(2)
    await nextTick()
    expect(ui.draftState).toBe('IDLE')
    expect(ui.records).toHaveLength(3)
    expect(ui.records[2]?.contactResistance).toBe(0)
    expect(ui.records[2]?.workOrder).toBe('aB-007 X')
    expect(ui.draft.workOrder).toBeNull()
  })
  it.each(['failure', 'uncertain'] as const)('automatically applies preset %s without clearing the draft', async outcome => {
    const ui = ready()
    ui.saveOutcome = outcome
    saving(ui)
    const pending = { ...ui.pending }
    await nextTick()
    expect(ui.records).toHaveLength(2)
    expect(ui.draft.workOrder).toBe('WO-20261026')
    expect(ui.pending).toEqual(pending)
    expect(ui.draftState).toBe(outcome === 'failure' ? 'IDLE' : 'SAVING')
    expect(ui.awaitingCheck).toBe(outcome === 'uncertain')
  })
  it('keeps uncertainty frozen after subsequent automatic ticks and resolves through reconciliation', async () => {
    const ui = ready()
    ui.saveOutcome = 'uncertain'
    saving(ui)
    await nextTick()
    ui.checkOutcome = 'conflict'
    ui.checkSave()
    ui.saveOutcome = 'success'
    await nextTick()
    expect(ui.awaitingCheck).toBe(true)
    expect(ui.records).toHaveLength(2)
    ui.checkOutcome = 'same'
    ui.checkSave()
    expect(ui.records).toHaveLength(3)
    expect(ui.draft.workOrder).toBeNull()
  })
  it('reports all six invalid fields, rejecting wrong types and result values', () => {
    const ui = ready()
    // Simulate malformed UI input; TypeScript alone cannot validate runtime values.
    Object.assign(ui.draft, { workOrder: 123, partNumber: '   ', contactResistance: '12', insulationResistance: NaN, withstandVoltage: Infinity, result: 'UNKNOWN' })
    ui.requestDraft('save')
    expect(ui.errors).toHaveLength(6)
    expect(ui.errors.join()).toContain('需要文本')
    expect(ui.errors.join()).toContain('PASS 或 FAIL')
    expect(ui.draftState).toBe('IDLE')
    expect(ui.dialog).toBeNull()
    expect(ui.records).toHaveLength(2)
  })
  it('does not let an old save callback finish a new attempt using the same pending ID', async () => {
    const ui = ready()
    saving(ui)
    ui.saveOutcome = 'failure'
    ui.finishSave()
    const pending = { ...ui.pending }
    ui.requestDraft('save')
    ui.confirmDialog()
    ui.saveOutcome = 'uncertain'
    await nextTick()
    expect(ui.pending).toEqual(pending)
    expect(ui.awaitingCheck).toBe(true)
    expect(ui.records).toHaveLength(2)
  })
  it('keeps storage untouched through automatic startup, save and failure', async () => {
    const storage = { getItem: vi.fn(), setItem: vi.fn(), removeItem: vi.fn(), clear: vi.fn() }
    vi.stubGlobal('localStorage', storage)
    const ui = ready()
    ui.toggleListening()
    await nextTick()
    saving(ui)
    await nextTick()
    ui.saveOutcome = 'failure'
    saving(ui)
    await nextTick()
    for (const method of Object.values(storage)) expect(method).not.toHaveBeenCalled()
  })
  it('starts with nullable fields, loading history and existing model states', () => {
    const ui = reactive(useMockUi())
    expect(Object.values(ui.draft)).toEqual([null, null, null, null, null, null])
    expect(ui.draftState).toBe('IDLE')
    expect(ui.microphone).toBe('IDLE')
    expect(ui.visibleRecords).toEqual([])
    expect(ui.historyWritable).toBe(false)
    ui.loadHistory('error')
    ui.updateField('workOrder', 'A-007')
    expect(ui.draft.workOrder).toBe('A-007')
    ui.requestDraft('save')
    expect(ui.dialog).toBeNull()
    ui.loadHistory('ready', true)
    expect(ui.visibleRecords).toEqual([])
    expect(ui.historyWritable).toBe(true)
    expect(ui.message).toContain('历史为空')
    expect(ui.message).not.toContain('读取失败')
  })
  it('edits and clears only the chosen field, preserves zero and result independence', () => {
    const ui = ready()
    const records = structuredClone(ui.records.map(r => ({ ...r })))
    ui.fillExample()
    ui.updateField('contactResistance', 0)
    expect(ui.draft.contactResistance).toBe(0)
    ui.updateField('contactResistance', null)
    expect(ui.draft.contactResistance).toBeNull()
    expect(ui.draft.result).toBe('PASS')
    expect(ui.draft.insulationResistance).toBe(200)
    expect(ui.records).toEqual(records)
    expect(ui.draft).not.toHaveProperty('unit')
  })
  it('shows every basic input error and preset errors without confirming invalid data', () => {
    const ui = ready()
    ui.requestDraft('save')
    expect(ui.errors).toHaveLength(6)
    expect(ui.draftState).toBe('IDLE')
    ui.fillExample()
    expect(ui.errors).toEqual([])
    ui.validationFailure = true
    ui.requestDraft('save')
    expect(ui.errors).toHaveLength(2)
    expect(ui.dialog).toBeNull()
    ui.validationFailure = false
    ui.updateField('contactResistance', -1)
    ui.requestDraft('save')
    expect(ui.errors.join()).toContain('有限非负数')
  })
  it('cancel save preserves draft; confirm save freezes it and only success adds a row', () => {
    const ui = ready()
    ui.fillExample()
    ui.requestDraft('save')
    const original = { ...ui.draft }
    ui.updateField('workOrder', 'invalid edit')
    expect(ui.draft).toEqual(original)
    ui.cancelDialog()
    expect(ui.draft).toEqual(original)
    ui.requestDraft('save')
    ui.confirmDialog()
    expect(ui.draftState).toBe('SAVING')
    expect(ui.records).toHaveLength(2)
    ui.requestDraft('draft-delete')
    ui.updateField('partNumber', null)
    expect(ui.draft).toEqual(original)
    ui.finishSave()
    expect(ui.records).toHaveLength(3)
    expect(ui.pending).toBeNull()
    expect(ui.draft.workOrder).toBeNull()
    expect(ui.draftState).toBe('IDLE')
  })
  it('reuses complete pending after explicit failure and invalidates it only on actual edits', () => {
    const ui = ready()
    saving(ui)
    const pending = { ...ui.pending }
    ui.saveOutcome = 'failure'
    ui.finishSave()
    expect(ui.draft.workOrder).toBe('WO-20261026')
    ui.updateField('workOrder', ui.draft.workOrder)
    ui.applyPreset({})
    ui.requestDraft('save')
    ui.cancelDialog()
    ui.requestDraft('save')
    ui.confirmDialog()
    expect(ui.pending).toEqual(pending)
    ui.finishSave()
    ui.updateField('workOrder', 'NEW')
    expect(ui.pending).toBeNull()
    ui.requestDraft('save')
    ui.confirmDialog()
    expect(ui.pending?.id).not.toBe(pending.id)
  })
  it.each(['conflict', 'error'] as const)('keeps uncertain save frozen on %s and prohibits bypassing reconciliation', outcome => {
    const ui = ready()
    saving(ui)
    const pending = { ...ui.pending }
    ui.saveOutcome = 'uncertain'
    ui.finishSave()
    ui.checkOutcome = outcome
    ui.checkSave()
    ui.saveOutcome = 'success'
    ui.finishSave()
    ui.openHistory('history-delete', 'demo-002')
    ui.loadHistory('ready', true)
    expect(ui.draftState).toBe('SAVING')
    expect(ui.awaitingCheck).toBe(true)
    expect(ui.pending).toEqual(pending)
    expect(ui.records).toHaveLength(2)
    expect(ui.dialog).toBeNull()
  })
  it.each(['same', 'absent'] as const)('resolves uncertainty from preset %s', outcome => {
    const ui = ready()
    saving(ui)
    ui.saveOutcome = 'uncertain'
    ui.finishSave()
    ui.checkOutcome = outcome
    ui.checkSave()
    expect(ui.draftState).toBe('IDLE')
    expect(ui.awaitingCheck).toBe(false)
    expect(ui.records).toHaveLength(outcome === 'same' ? 3 : 2)
    expect(ui.pending === null).toBe(outcome === 'same')
  })
  it('cancel draft delete keeps pending; confirm delete clears draft and text without changing history', () => {
    const ui = ready()
    saving(ui)
    ui.saveOutcome = 'failure'
    ui.finishSave()
    const pending = { ...ui.pending }
    ui.requestDraft('draft-delete')
    ui.cancelDialog()
    expect(ui.pending).toEqual(pending)
    ui.requestDraft('draft-delete')
    ui.confirmDialog()
    expect(ui.pending).toBeNull()
    expect(ui.draft.workOrder).toBeNull()
    expect(ui.records).toHaveLength(2)
  })
  it('listens before recording and drops interim text, then merges only preset mentioned fields', () => {
    const ui = ready()
    ui.toggleListening()
    expect(ui.microphone).toBe('IDLE')
    expect(ui.starting).toBe(true)
    ui.toggleListening()
    ui.finishStartup()
    expect(ui.microphone).toBe('LISTENING')
    expect(ui.textComplete).toBe(false)
    ui.startInput()
    ui.transcript()
    expect(ui.draft.workOrder).toBeNull()
    ui.updateField('partNumber', 'manual-007')
    ui.toggleListening()
    expect(ui.microphone).toBe('RECORDING')
    ui.stopInput()
    expect(ui.microphone).toBe('LISTENING')
    expect(ui.interimText).toBe('')
    ui.updateField('partNumber', 'blocked')
    ui.finishParse()
    expect(ui.draft.workOrder).toBe('WO-20261026')
    expect(ui.draft.partNumber).toBe('manual-007')
    ui.startInput()
    expect(ui.confirmedText).toBe('')
  })
  it('cancels startup, ignores late completion and supports simulated startup failure', () => {
    const ui = ready()
    ui.toggleListening()
    ui.cancelStartup()
    ui.finishStartup()
    expect(ui.microphone).toBe('IDLE')
    ui.speechFailure = true
    ui.toggleListening()
    ui.finishStartup()
    expect(ui.starting).toBe(false)
    expect(ui.microphone).toBe('IDLE')
    expect(ui.message).toContain('启动失败')
    expect(ui.editable).toBe(true)
  })
  it('finishes an empty recording once without inventing fields', () => {
    const ui = ready()
    recording(ui)
    ui.stopInput()
    ui.stopInput()
    ui.finishParse()
    expect(ui.textComplete).toBe(true)
    expect(ui.draft.workOrder).toBeNull()
  })
  it('processes final text before a requested save and does not queue recording voice commands', () => {
    const ui = ready()
    ui.fillExample()
    recording(ui)
    ui.transcript()
    ui.command('SAVE')
    expect(ui.dialog).toBeNull()
    ui.requestDraft('save')
    expect(ui.processing).toBe(true)
    expect(ui.dialog).toBeNull()
    ui.finishParse()
    expect(ui.dialog).toBe('save')
  })
  it('retains confirmed text on interruption and draft on parse failure, rejects old results', () => {
    const ui = ready()
    recording(ui)
    ui.transcript()
    ui.interruptSpeech()
    expect(ui.microphone).toBe('IDLE')
    expect(ui.confirmedText).not.toBe('')
    ui.parseFailure = true
    ui.finishParse()
    expect(ui.processing).toBe(false)
    expect(ui.draft.workOrder).toBeNull()
    ui.requestDraft('draft-delete')
    ui.confirmDialog()
    ui.lateResult()
    expect(ui.draft.workOrder).toBeNull()
    expect(ui.confirmedText).toBe('')
  })
  it('applies filters only on query, prunes invisible selection and never restores it implicitly', () => {
    const ui = ready()
    ui.select('demo-002')
    expect(ui.partiallySelected).toBe(true)
    ui.selectAll()
    expect(ui.allSelected).toBe(true)
    ui.filters.workOrder = '  wo-20261025  '
    expect(ui.visibleRecords).toHaveLength(2)
    ui.query()
    expect(ui.visibleRecords.map(r => r.id)).toEqual(['demo-001'])
    expect(ui.selectedIds).toEqual(['demo-001'])
    ui.selectAll()
    expect(ui.selectedIds).toEqual([])
    ui.selectAll()
    ui.filters.workOrder = ''
    ui.query()
    expect(ui.selectedIds).toEqual(['demo-001'])
  })
  it('keeps original order and query results on rejected query, implements stable allowed sorting', () => {
    const ui = ready()
    ui.records = ui.records.map((r, i) => ({ ...r, workOrder: i ? 'A10' : 'A2' }))
    ui.filters.sort = 'workOrder:asc'
    ui.query()
    expect(ui.visibleRecords.map(r => r.workOrder)).toEqual(['A10', 'A2'])
    expect(ui.records.map(r => r.workOrder)).toEqual(['A2', 'A10'])
    ui.filters.workOrder = 'missing'
    ui.queryFailure = true
    ui.query()
    expect(ui.visibleRecords).toHaveLength(2)
    ui.queryFailure = false
    ui.filters.createdFrom = '2026-10-27T00:00:00'
    ui.filters.createdTo = '2026-10-26T00:00:00'
    ui.query()
    expect(ui.visibleRecords).toHaveLength(2)
  })
  it('isolates history edit/cancel and retains incomplete form on simulated failure', () => {
    const ui = ready()
    const original = { ...ui.records[0] }
    ui.openHistory('history-edit', 'demo-002')
    ui.updateHistory('partNumber', 'changed')
    expect(ui.records[0]).toEqual(original)
    ui.cancelDialog()
    ui.openHistory('history-edit', 'demo-002')
    expect(ui.historyEditFields.partNumber).toBe(original.partNumber)
    ui.updateHistory('partNumber', null)
    ui.confirmHistory()
    expect(ui.dialog).toBe('history-edit')
    expect(ui.records[0]).toEqual(original)
    ui.updateHistory('partNumber', 'NEW')
    ui.operationFailure = true
    ui.confirmHistory()
    expect(ui.records[0]).toEqual(original)
    expect(ui.historyEditFields.partNumber).toBe('NEW')
    ui.operationFailure = false
    ui.confirmHistory()
    expect(ui.records[0]?.partNumber).toBe('NEW')
    expect(ui.records[0]?.createdAt).toBe(original.createdAt)
    expect(ui.draft.workOrder).toBeNull()
  })
  it('deletes history only after successful confirmation and cleans selected IDs', () => {
    const ui = ready()
    ui.select('demo-002')
    ui.openHistory('history-delete', 'demo-002')
    ui.operationFailure = true
    ui.confirmDialog()
    expect(ui.selectedIds).toEqual(['demo-002'])
    expect(ui.records).toHaveLength(2)
    ui.operationFailure = false
    ui.confirmDialog()
    expect(ui.records).toHaveLength(1)
    expect(ui.selectedIds).toEqual([])
  })
  it('exports selected current data or all data independent of filter and preserves data on failure', () => {
    const ui = ready()
    ui.filters.workOrder = '20261025'
    ui.query()
    ui.selectAll()
    ui.exportRecords(false)
    expect(ui.message).toContain('1 条')
    ui.exportRecords(true)
    expect(ui.message).toContain('2 条')
    ui.operationFailure = true
    ui.exportRecords(true)
    expect(ui.records).toHaveLength(2)
    expect(ui.selectedIds).toEqual(['demo-001'])
    ui.loadHistory('ready', true)
    ui.exportRecords(true)
    expect(ui.message).toContain('没有可模拟导出')
  })
  it('does not access storage, microphone or download APIs across the main workflow', () => {
    const storage = { getItem: vi.fn(), setItem: vi.fn(), removeItem: vi.fn(), clear: vi.fn() }
    const download = vi.fn()
    vi.stubGlobal('localStorage', storage)
    vi.stubGlobal('URL', { createObjectURL: download })
    const speech = vi.fn()
    vi.stubGlobal('SpeechRecognition', speech)
    const ui = ready()
    saving(ui)
    ui.finishSave()
    recording(ui)
    ui.transcript()
    ui.stopInput()
    ui.finishParse()
    ui.selectAll()
    ui.exportRecords(true)
    ui.loadHistory('error')
    for (const method of Object.values(storage)) expect(method).not.toHaveBeenCalled()
    expect(download).not.toHaveBeenCalled()
    expect(speech).not.toHaveBeenCalled()
    const fresh = ready()
    expect(fresh.records).toHaveLength(2)
    expect(fresh.draft.workOrder).toBeNull()
  })
})
